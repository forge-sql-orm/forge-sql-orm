// The "import" export condition used to point at the CommonJS build (dist/index.js). Its
// `default` export lives on `module.exports.default`, so ES-module consumers (Node ESM,
// "type": "module" apps, strict-ESM webpack) got the whole `module.exports` object as the
// default import and `new ForgeSQL()` failed with "... is not a constructor".
//
// This writes dist/esm/index.js: a thin ES module that re-exports the *same* CommonJS module
// (no duplicated code, so module-level singletons such as the cache/metadata contexts stay
// shared with CommonJS consumers) and maps the default export correctly. Named exports are
// listed explicitly so Node and bundlers do not depend on CommonJS export detection.
import { existsSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { join } from "node:path";

const SKIPPED_EXPORTS = new Set(["default", "__esModule"]);

function isExportableName(name) {
  if (SKIPPED_EXPORTS.has(name) || !/^[A-Za-z_$][\w$]*$/.test(name)) return false;
  try {
    new Function(`const ${name} = 0;`);
    return true;
  } catch {
    return false; // reserved word
  }
}

export function writeEsmEntry(distDir) {
  const cjsEntry = join(distDir, "index.js");
  if (!existsSync(cjsEntry)) {
    throw new Error(`Build the CommonJS output first, missing ${cjsEntry}`);
  }
  const cjs = createRequire(import.meta.url)(cjsEntry);
  if (typeof cjs.default !== "function") {
    throw new Error("Expected the CommonJS build to expose the ORM class as `default`");
  }
  const names = Object.keys(cjs).filter(isExportableName).sort();
  const source = [
    "// Generated by scripts/write-esm-entry.mjs - do not edit.",
    'import cjs from "../index.js";',
    "",
    "export default cjs.default;",
    ...names.map((name) => `export const ${name} = cjs.${name};`),
    "",
  ].join("\n");
  writeFileSync(join(distDir, "esm", "index.js"), source);
  return names.length;
}
